mod k6;

use std::fs::OpenOptions;
use std::io::Write;
use std::path::Path;

use crate::cli::{ConvertAction, ConvertArgs, ConvertK6Args};
use crate::error::CliError;

pub fn run(args: ConvertArgs) -> Result<(), CliError> {
    match args.action {
        ConvertAction::K6(args) => run_k6(args),
    }
}

fn run_k6(args: ConvertK6Args) -> Result<(), CliError> {
    let source = std::fs::read_to_string(&args.input).map_err(|e| {
        CliError::new(format!(
            "failed to read k6 script '{}'",
            args.input.display()
        ))
        .cause(e.to_string())
    })?;
    let converted = k6::convert(&source).map_err(|e| {
        CliError::new(format!("cannot convert '{}'", args.input.display()))
            .cause(e)
            .hint("keep dynamic scenarios on `perfscale run --k6`, or simplify them to the documented static subset")
            .docs("cli/commands.md#perfscale-convert-k6")
    })?;
    if args.test == args.config {
        return Err(CliError::new(
            "test and config outputs must be different files",
        ));
    }
    if !args.force {
        for path in [&args.test, &args.config] {
            if path.exists() {
                return Err(CliError::new(format!(
                    "output '{}' already exists — choose another path or use --force",
                    path.display()
                )));
            }
        }
    }
    let name = args
        .input
        .file_name()
        .map(|s| s.to_string_lossy().replace(['\r', '\n'], " "))
        .unwrap_or_else(|| "script.js".into());
    let test = format!(
        "# Generated by `perfscale convert k6` from {name}.\n{}",
        converted.test_yaml
    );
    let config = format!(
        "# Generated by `perfscale convert k6` from {name}.\n{}",
        converted.config_yaml
    );
    write_output(&args.test, &test, args.force)?;
    write_output(&args.config, &config, args.force)?;
    println!("wrote {}", args.test.display());
    println!("wrote {}", args.config.display());
    println!(
        "next: perfscale lint '{}' '{}'",
        args.test.display(),
        args.config.display()
    );
    Ok(())
}

fn write_output(path: &Path, contents: &str, force: bool) -> Result<(), CliError> {
    let write = || -> std::io::Result<()> {
        if force {
            std::fs::write(path, contents)
        } else {
            let mut file = OpenOptions::new().write(true).create_new(true).open(path)?;
            file.write_all(contents.as_bytes())
        }
    };
    write().map_err(|e| {
        CliError::new(format!("failed to write '{}'", path.display())).cause(e.to_string())
    })
}
