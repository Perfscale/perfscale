use std::io::Write;

use assert_cmd::Command;
use predicates::prelude::*;

fn cmd() -> Command {
    Command::cargo_bin("perfscale").unwrap()
}

fn script() -> tempfile::NamedTempFile {
    let mut script = tempfile::Builder::new().suffix(".js").tempfile().unwrap();
    writeln!(
        script,
        r#"
        import http from 'k6/http';
        import {{ check }} from 'k6';
        export const options = {{ vus: 1, duration: '1s' }};
        export default function () {{
          const res = http.get('https://example.com');
          check(res, {{ ok: (r) => r.status === 200 }});
        }}
    "#
    )
    .unwrap();
    script
}

#[test]
fn convert_k6_writes_lintable_test_and_config() {
    let dir = tempfile::tempdir().unwrap();
    let script = script();
    let test = dir.path().join("api.yaml");
    let config = dir.path().join("load.yaml");
    cmd()
        .args(["convert", "k6", script.path().to_str().unwrap(), "-t"])
        .arg(&test)
        .arg("-c")
        .arg(&config)
        .assert()
        .success()
        .stdout(predicate::str::contains("next: perfscale lint"));
    cmd()
        .arg("lint")
        .arg(&test)
        .arg(&config)
        .assert()
        .success()
        .stdout(predicate::str::contains("(test definition) — ok"))
        .stdout(predicate::str::contains("(config) — ok"));
    let generated = std::fs::read_to_string(test).unwrap();
    assert!(generated.starts_with("# Generated by `perfscale convert k6`"));
    assert!(generated.contains("use: std/http@v1"));
}

#[test]
fn convert_k6_refuses_overwrite_until_forced() {
    let dir = tempfile::tempdir().unwrap();
    let script = script();
    let test = dir.path().join("test.yaml");
    let config = dir.path().join("config.yaml");
    std::fs::write(&test, "keep me").unwrap();
    cmd()
        .args(["convert", "k6", script.path().to_str().unwrap(), "-t"])
        .arg(&test)
        .arg("-c")
        .arg(&config)
        .assert()
        .failure()
        .stderr(predicate::str::contains("already exists"));
    assert_eq!(std::fs::read_to_string(&test).unwrap(), "keep me");
    assert!(!config.exists());
    cmd()
        .args(["convert", "k6", script.path().to_str().unwrap(), "-t"])
        .arg(&test)
        .arg("-c")
        .arg(&config)
        .arg("--force")
        .assert()
        .success();
    assert!(std::fs::read_to_string(test).unwrap().contains("steps:"));
}

#[test]
fn convert_k6_failure_does_not_create_outputs() {
    let dir = tempfile::tempdir().unwrap();
    let mut script = tempfile::Builder::new().suffix(".js").tempfile().unwrap();
    writeln!(script, "export const options = {{ vus: 1, duration: '1s' }}; export default function () {{ if (true) {{}} }}").unwrap();
    let test = dir.path().join("test.yaml");
    let config = dir.path().join("config.yaml");
    cmd()
        .args(["convert", "k6", script.path().to_str().unwrap(), "-t"])
        .arg(&test)
        .arg("-c")
        .arg(&config)
        .assert()
        .failure()
        .stderr(predicate::str::contains("line 1"))
        .stderr(predicate::str::contains("unsupported statement"));
    assert!(!test.exists());
    assert!(!config.exists());
}
