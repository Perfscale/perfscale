/// Table sorting: click a header of a `data-sortable` table to sort its rows
/// (numeric-aware). That is the only script in the document.
const JS: &str = r#"document.querySelectorAll('table[data-sortable] th').forEach(function(th){
  th.addEventListener('click',function(){
    var table=th.closest('table'),idx=Array.prototype.indexOf.call(th.parentNode.children,th);
    var dir=th.dataset.dir==='asc'?'desc':'asc';
    th.parentNode.querySelectorAll('th').forEach(function(h){delete h.dataset.dir;});
    th.dataset.dir=dir;
    var rows=Array.prototype.slice.call(table.tBodies[0].rows);
    rows.sort(function(a,b){
      var x=a.cells[idx].textContent.trim(),y=b.cells[idx].textContent.trim();
      var nx=parseFloat(x),ny=parseFloat(y);
      var cmp=(!isNaN(nx)&&!isNaN(ny))?nx-ny:x.localeCompare(y);
      return dir==='asc'?cmp:-cmp;
    });
    rows.forEach(function(r){table.tBodies[0].appendChild(r);});
  });
});"#;

#[cfg(test)]
mod tests {
    use super::*;
    use crate::metrics::Metrics;
    use crate::report::v1::{build_report_v1, ReportContext};
    use crate::step::actions::HttpSample;
    use crate::step::thresholds::{ThresholdCheck, ThresholdsSummary};
    use serde_json::Map;

    fn ctx() -> ReportContext {
        ReportContext {
            run_id: "run-42".into(),
            engine: "native".into(),
            perfscale_version: "0.0.0-test".into(),
            vus: Some(2),
            started_at: "2026-10-20T00:00:00Z".into(),
            wall_secs: 10.0,
            labels: Map::from_iter([("testid".to_string(), serde_json::json!("smoke"))]),
            step_order: vec![("hit".into(), "std/http@v1".into())],
            iterations: 10,
            vus_gauge: 2,
            max_samples: Some(5),
        }
    }

    fn report() -> ReportV1 {
        let mut m = Metrics::default();
        for i in 0..10u64 {
            m.record(&HttpSample {
                duration_ms: 1.0 + i as f64,
                status: 200,
                failed: i % 5 == 4,
            });
            m.record_step("hit", 1.0 + i as f64, i % 5 == 4);
        }
        let t = ThresholdsSummary {
            status: "fail".into(),
            message: "x".into(),
            violations: vec![],
            checks: vec![
                ThresholdCheck {
                    metric: "http_req_duration".into(),
                    expr: "p95<0".into(),
                    actual: 10.0,
                    pass: false,
                },
                ThresholdCheck {
                    metric: "http_req_failed".into(),
                    expr: "rate<0.05".into(),
                    actual: 0.0,
                    pass: true,
                },
            ],
        };
        build_report_v1(&m, Some(&t), None, &ctx())
    }

    /// Cheap structural sanity: every container tag we emit is balanced.
    fn assert_balanced(html: &str) {
        for tag in [
            "html", "head", "body", "main", "table", "thead", "tbody", "tr", "section", "details",
            "ul", "li", "header", "footer", "style", "script",
        ] {
            // `<tag>` (no attrs) or `<tag …>`; `<head>` must not match `<header>`.
            let open = html.matches(&format!("<{tag}>")).count()
                + html.matches(&format!("<{tag} ")).count();
            let close = html.matches(&format!("</{tag}>")).count();
            assert_eq!(open, close, "tag <{tag}> unbalanced ({open} vs {close})");
        }
    }

    #[test]
    fn html_is_one_self_contained_document() {
        let html = report().to_html();
        assert_eq!(html.matches("<html").count(), 1, "{html}");
        assert_eq!(html.matches("</html>").count(), 1);
        assert!(html.starts_with("<!DOCTYPE html>"));
        // No external references — the file must open offline.
        assert!(!html.contains("src=\"http"), "{html}");
        assert!(!html.contains("href=\"http"), "{html}");
        assert!(!html.contains("@import"), "{html}");
        assert_balanced(&html);
    }

    #[test]
    fn html_carries_identity_steps_verdicts_and_metrics() {
        let html = report().to_html();
        assert!(html.contains("run-42"), "{html}");
        assert!(html.contains(">native<"), "{html}");
        assert!(html.contains("0.0.0-test"), "{html}");
        assert!(html.contains("testid"), "{html}");
        assert!(html.contains(">hit<"), "{html}");
        assert!(html.contains("std/http@v1"), "{html}");
        assert!(html.contains("p95&lt;0"), "{html}");
        assert!(html.contains("http_req_duration"), "{html}");
        assert!(html.contains("http_reqs"), "{html}");
        // Truncated raw samples (5 of 10 recorded) are flagged.
        assert!(html.contains(">truncated</span>"), "{html}");
        assert!(html.contains("<svg class=\"spark\""), "{html}");
        // Verdicts summary: one pass, one fail.
        assert!(html.contains("✓ 1 pass"), "{html}");
        assert!(html.contains("✗ 1 fail"), "{html}");
    }

    #[test]
    fn html_escapes_user_controlled_strings() {
        let mut c = ctx();
        c.step_order = vec![("evil<script>alert(1)</script>".into(), "std/http@v1".into())];
        let mut m = Metrics::default();
        m.record_step("evil<script>alert(1)</script>", 1.0, false);
        let r = build_report_v1(&m, None, None, &c);
        let html = r.to_html();
        // The step name must never appear raw; the only <script> block is ours.
        assert!(!html.contains("evil<script>"), "{html}");
        assert!(html.contains("evil&lt;script&gt;"), "{html}");
        assert_eq!(html.matches("<script>").count(), 1, "{html}");
        assert!(!html.contains("alert(1)</script>"), "{html}");
        assert_balanced(&html);
    }

    #[test]
    fn html_handles_an_empty_report() {
        let r = build_report_v1(&Metrics::default(), None, None, &ctx());
        let html = r.to_html();
        assert!(html.contains("no thresholds evaluated"), "{html}");
        assert!(html.contains("no per-step aggregates"), "{html}");
        assert_balanced(&html);
    }

    #[test]
    fn gauges_render_last_value_and_ts() {
        let mut r = build_report_v1(&Metrics::default(), None, None, &ctx());
        r.metrics.push(MetricFamilyReport {
            name: "gpu_utilization_pct".into(),
            family: "gpu".into(),
            kind: "gauge".into(),
            unit: "%".into(),
            description: "GPU gauge".into(),
            recorded: true,
            series: vec![MetricSeries {
                labels: Map::from_iter([("gpu".to_string(), serde_json::json!("0"))]),
                value: Some(42.0),
                ts: Some("2026-10-20T00:00:02.000Z".into()),
                ..MetricSeries::default()
            }],
        });
        let html = r.to_html();
        assert!(html.contains("gpu=\"0\""), "{html}");
        assert!(html.contains("2026-10-20T00:00:02.000Z"), "{html}");
    }
}
